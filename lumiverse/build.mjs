// Builds lumiverse/frontend.js (the Lumiverse extension) from lumiverse/frontend.src.js plus the
// starters, dependencies and wing → tracker table in src/map.js, so both apps share one source of truth.
// Usage: node lumiverse/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const map = await import(pathToFileURL(join(here, '..', 'src', 'map.js')).href);
const data = { STARTERS: map.STARTERS, REQUIRES: map.REQUIRES, ADVISORIES: map.ADVISORIES, WING_TRACKER: map.WING_TRACKER };
for (const [k, v] of Object.entries(data)) if (!v) throw new Error(`src/map.js has no ${k}`);
const src = readFileSync(join(here, 'frontend.src.js'), 'utf8');
if (!src.includes('/*@DATA@*/ null')) throw new Error('data placeholder missing');
const out = '// GENERATED by lumiverse/build.mjs from frontend.src.js and src/map.js. Edit those, not this file.\n'
  + src.replace('/*@DATA@*/ null', JSON.stringify(data));
writeFileSync(join(here, 'frontend.js'), out);
console.log(`frontend.js: ${out.length} bytes, ${data.STARTERS.length} starters`);
